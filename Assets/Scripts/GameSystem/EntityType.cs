    /// </summary>
    public enum EntityType
    {
        /// <summary>
        /// The first player character.
        /// </summary>
        Character1,
        /// <summary>
        /// The second player character.
        /// </summary>
        Character2,
        /// <summary>
        /// The third player character.
        /// </summary>
        Character3,
        /// <summary>
        /// The fourth player character.
        /// </summary>
        Character4,
        /// <summary>
        /// The boss entity.
        /// </summary>
        Boss
    }
}
